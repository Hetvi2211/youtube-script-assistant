"""
exporter.py
Handles exporting generated script and content package into TXT, DOCX, and PDF files.
"""

from __future__ import annotations

import io
from typing import Any, Dict, Optional


def export_to_txt(content: str) -> bytes:
    """Export text content as UTF-8 encoded bytes."""
    return content.encode("utf-8")


def export_to_docx(content: str, title: str = "YouTube Content Package") -> bytes:
    """Export content into a formatted Microsoft Word (.docx) document as bytes."""
    try:
        from docx import Document
        from docx.shared import Inches, Pt, RGBColor
    except ImportError:
        raise ImportError("python-docx is required for Word export: pip install python-docx")

    doc = Document()

    # Document Header / Title
    title_p = doc.add_paragraph()
    title_run = title_p.add_run(title)
    title_run.font.size = Pt(20)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(178, 34, 34)  # Crimson / YouTube red theme

    # Add subtitle
    sub_p = doc.add_paragraph()
    sub_run = sub_p.add_run("Generated by YouTube Script Writing Assistant")
    sub_run.font.italic = True
    sub_run.font.size = Pt(10)
    sub_run.font.color.rgb = RGBColor(128, 128, 128)

    doc.add_paragraph("―" * 50)

    # Process text sections
    lines = content.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        if not line:
            i += 1
            continue

        # Check for Section Headers
        is_major_header = line.isupper() and len(line) < 40 and any(h in line for h in [
            "TITLE", "HOOK", "SCRIPT", "DESCRIPTION", "KEYWORDS", "TAGS", "HASHTAGS", "CALL-TO-ACTION", "SCENE BREAKDOWN"
        ])
        is_md_header = line.startswith("#")

        if is_major_header or is_md_header:
            clean_header = line.lstrip("#").strip().rstrip(":")
            h_p = doc.add_paragraph()
            h_run = h_p.add_run(clean_header)
            h_run.font.size = Pt(14)
            h_run.font.bold = True
            h_run.font.color.rgb = RGBColor(30, 30, 30)
            h_p.paragraph_format.space_before = Pt(12)
            h_p.paragraph_format.space_after = Pt(4)
        else:
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(2)
            p.paragraph_format.space_after = Pt(2)
            p_run = p.add_run(line)
            p_run.font.size = Pt(11)

        i += 1

    file_stream = io.BytesIO()
    doc.save(file_stream)
    return file_stream.getvalue()


def export_to_pdf(content: str, title: str = "YouTube Content Package") -> bytes:
    """
    Export content into a well-formatted PDF document using ReportLab.
    Falls back to fpdf2 if ReportLab is unavailable.
    """
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib import colors
        import xml.sax.saxutils

        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=letter,
            rightMargin=54,
            leftMargin=54,
            topMargin=54,
            bottomMargin=54,
        )

        styles = getSampleStyleSheet()
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontSize=18,
            leading=22,
            textColor=colors.HexColor("#CC0000"),
            spaceAfter=6,
        )
        subtitle_style = ParagraphStyle(
            "DocSubTitle",
            parent=styles["Normal"],
            fontSize=9,
            leading=12,
            textColor=colors.HexColor("#666666"),
            spaceAfter=12,
        )
        header_style = ParagraphStyle(
            "SectionHeader",
            parent=styles["Heading2"],
            fontSize=13,
            leading=16,
            textColor=colors.HexColor("#222222"),
            spaceBefore=12,
            spaceAfter=4,
            keepWithNext=True,
        )
        body_style = ParagraphStyle(
            "BodyDark",
            parent=styles["Normal"],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#333333"),
            spaceAfter=4,
        )

        story = []
        story.append(Paragraph(xml.sax.saxutils.escape(title), title_style))
        story.append(Paragraph("Generated by YouTube Script Writing Assistant", subtitle_style))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#DDDDDD"), spaceAfter=12))

        lines = content.splitlines()
        for line in lines:
            line_str = line.strip()
            if not line_str:
                story.append(Spacer(1, 4))
                continue

            # Section headers
            is_major_header = line_str.isupper() and len(line_str) < 40 and any(h in line_str for h in [
                "TITLE", "HOOK", "SCRIPT", "DESCRIPTION", "KEYWORDS", "TAGS", "HASHTAGS", "CALL-TO-ACTION", "SCENE BREAKDOWN"
            ])
            is_md_header = line_str.startswith("#")

            escaped = xml.sax.saxutils.escape(line_str)
            if is_major_header or is_md_header:
                clean_h = xml.sax.saxutils.escape(line_str.lstrip("#").strip().rstrip(":"))
                story.append(Paragraph(f"<b>{clean_h}</b>", header_style))
            else:
                story.append(Paragraph(escaped, body_style))

        doc.build(story)
        return buffer.getvalue()

    except ImportError:
        # Fallback to fpdf2
        from fpdf import FPDF

        pdf = FPDF()
        pdf.add_page()
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.set_font("Helvetica", "B", 16)
        pdf.set_text_color(204, 0, 0)
        pdf.cell(0, 10, title, ln=True)

        pdf.set_font("Helvetica", "I", 9)
        pdf.set_text_color(100, 100, 100)
        pdf.cell(0, 6, "Generated by YouTube Script Writing Assistant", ln=True)
        pdf.ln(4)

        pdf.set_text_color(0, 0, 0)
        pdf.set_font("Helvetica", "", 10)

        for line in content.splitlines():
            # encode ascii/latin-1 safe for fpdf default fonts
            safe_line = line.encode("latin-1", "replace").decode("latin-1")
            if safe_line.isupper() and len(safe_line) < 40:
                pdf.set_font("Helvetica", "B", 12)
                pdf.ln(2)
                pdf.cell(0, 6, safe_line, ln=True)
                pdf.set_font("Helvetica", "", 10)
            else:
                pdf.multi_cell(0, 5, safe_line)

        return pdf.output()
